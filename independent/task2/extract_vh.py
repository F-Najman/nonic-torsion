# Parse van Hoeij's LowDegreePlaces (read-only path given as argv[1]) and write a Magma data file
# with all degree-9 entries for the levels in question.  Own parser; does not use Codex JSON.
import sys, re, hashlib
src = sys.argv[1]; out = sys.argv[2]
data = open(src,'rb').read()
print("sha256", hashlib.sha256(data).hexdigest())
lines = data.decode().splitlines()
ents = []
for i,l in enumerate(lines, start=1):
    m = re.match(r'N = (\d+), degv = 9,(.*)\[(.*) = 0, (.*) = 0\]\s*$', l)
    if not m: continue
    N = int(m.group(1)); extra = m.group(2); eqx = m.group(3); eqxy = m.group(4)
    ents.append((i, N, extra.strip(), eqx, eqxy))
print("degree-9 entries:", len(ents))
print("levels:", [e[1] for e in ents])
with open(out,'w') as F:
    F.write("// generated by extract_vh.py from %s\n" % src)
    F.write("VH := [* *];\n")
    for (i,N,extra,eqx,eqxy) in ents:
        F.write('Append(~VH, <%d, %d, "%s", %s, %s>);\n' % (i, N, extra.replace('"',''), eqx, eqxy))
